'use client';
import { useState, useEffect } from 'react';
import JSZip from 'jszip';
import hljs from 'highlight.js';
import 'highlight.js/styles/github-dark.css';
import { Copy, Download, CheckCircle2 } from 'lucide-react';
import { toast } from 'sonner';

const LOADING_MESSAGES = [
  "🔍 Analyzing your request...",
  "📝 Writing plugin architecture...",
  "☕ Generating Java code...",
  "📋 Creating plugin.yml...",
  "🔧 Building pom.xml...",
  "⚙️ Writing config files...",
  "✅ Almost done..."
];

export default function CodeViewer({ isGenerating, files, pluginName, providerName }) {
  const [activeTab, setActiveTab] = useState(null);
  const [copiedStates, setCopiedStates] = useState({});
  const [loadingMsgIdx, setLoadingMsgIdx] = useState(0);

  // Cycle loading messages
  useEffect(() => {
    let interval;
    if (isGenerating) {
      setLoadingMsgIdx(0);
      interval = setInterval(() => {
        setLoadingMsgIdx(prev => (prev < LOADING_MESSAGES.length - 1 ? prev + 1 : prev));
      }, 1500);
    }
    return () => clearInterval(interval);
  }, [isGenerating]);

  // Select first tab when files change
  useEffect(() => {
    if (files && Object.keys(files).length > 0 && !activeTab) {
      setActiveTab(Object.keys(files)[0]);
    }
  }, [files, activeTab]);

  const handleCopy = (content, path) => {
    navigator.clipboard.writeText(content);
    setCopiedStates({ ...copiedStates, [path]: true });
    toast.success('Code copied to clipboard!');
    setTimeout(() => {
      setCopiedStates({ ...copiedStates, [path]: false });
    }, 2000);
  };

  const handleDownloadZip = async () => {
    if (!files || !pluginName) return;
    
    const zip = new JSZip();
    
    Object.entries(files).forEach(([path, content]) => {
      zip.file(path, content);
    });
    
    zip.file('README.txt', `${pluginName} - Generated by CIY (Craft It Yourself)\n\nVisit ciy.gg to generate more plugins!\n\nHOW TO BUILD:\n1. Install Java 21 and Maven\n2. Run: mvn clean package\n3. Find your JAR in target/ folder\n4. Drop JAR in your server's plugins/ folder\n5. Restart server\n\nGenerated on: ${new Date().toLocaleDateString()}`);
    
    const blob = await zip.generateAsync({ type: 'blob' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${pluginName.replace(/\s+/g, '-')}-CIY.zip`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('ZIP file downloaded successfully!');
  };

  const getHighlightLanguage = (path) => {
    if (!path) return 'plaintext';
    if (path.endsWith('.java')) return 'java';
    if (path.endsWith('.yml') || path.endsWith('.yaml')) return 'yaml';
    if (path.endsWith('.xml')) return 'xml';
    if (path.endsWith('.md')) return 'markdown';
    return 'plaintext';
  };

  if (isGenerating) {
    return (
      <div className="flex flex-col items-center justify-center h-full min-h-[500px] border border-border border-dashed rounded-xl bg-surface/50 p-8">
        <div className="w-16 h-16 border-4 border-primary border-t-transparent rounded-full animate-spin mb-6"></div>
        <h3 className="text-xl font-bold text-white mb-2">Generating Plugin...</h3>
        <p className="text-primary font-medium tracking-wide animate-pulse">{LOADING_MESSAGES[loadingMsgIdx]}</p>
      </div>
    );
  }

  if (!files || Object.keys(files).length === 0) {
    return (
      <div className="flex flex-col items-center justify-center h-full min-h-[500px] border border-border border-dashed rounded-xl bg-surface/50 p-8 text-center">
        <div className="text-6xl mb-6">🧱</div>
        <h3 className="text-xl font-bold text-white mb-2">Your plugin will appear here</h3>
        <p className="text-white/50 max-w-xs">Describe your plugin in the prompt panel and click Generate</p>
      </div>
    );
  }

  const activeContent = files[activeTab] || '';
  const setupInstructions = files['SETUP.md'] || '';

  return (
    <div className="flex flex-col h-full flex-grow min-h-[600px] rounded-xl border border-border bg-surface overflow-hidden">
      {/* Top Bar */}
      <div className="p-4 border-b border-border flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 bg-[#151515]">
        <div className="flex items-center gap-3">
          <h2 className="font-semibold text-primary text-lg">{pluginName || 'Generated Plugin'}</h2>
          <span className="bg-primary/10 text-primary border border-primary/20 text-xs px-2 py-1 rounded-full flex items-center gap-1">
            <CheckCircle2 size={12} /> Success
          </span>
          {providerName && (
            <span className="text-xs text-white/40 ml-2 hidden sm:block">📝 Powered by {providerName}</span>
          )}
        </div>
        
        <div className="flex flex-col items-end">
          <button 
            onClick={handleDownloadZip}
            className="flex items-center gap-2 bg-primary hover:bg-primary-hover text-white px-4 py-2 rounded font-medium text-sm transition-colors shadow-[0_0_10px_rgba(34,197,94,0.2)]"
          >
            <Download size={16} />
            Download All Files (.zip)
          </button>
          <span className="text-[10px] text-white/40 mt-1">Compiled JAR not included — build with Maven</span>
        </div>
      </div>

      {/* Tabs */}
      <div className="flex overflow-x-auto border-b border-border bg-[#0d0d0d] hide-scrollbar">
        {Object.keys(files).map((path) => (
          <button
            key={path}
            onClick={() => setActiveTab(path)}
            className={`px-4 py-3 text-sm font-mono whitespace-nowrap border-b-2 transition-colors ${
              activeTab === path 
                ? 'border-primary text-primary bg-primary/5' 
                : 'border-transparent text-white/60 hover:text-white hover:bg-white/5'
            }`}
          >
            {path.split('/').pop()}
          </button>
        ))}
      </div>

      {/* Code Display */}
      <div className="relative flex-grow bg-code overflow-hidden flex flex-col group">
        <div className="absolute right-4 top-4 z-10 opacity-0 group-hover:opacity-100 transition-opacity">
          <button 
            onClick={() => handleCopy(activeContent, activeTab)}
            className="p-2 bg-surface/80 backdrop-blur border border-border rounded text-white/70 hover:text-white"
          >
            {copiedStates[activeTab] ? <CheckCircle2 size={18} className="text-primary" /> : <Copy size={18} />}
          </button>
        </div>
        
        <div className="flex-grow overflow-auto p-4 custom-scrollbar">
          <pre className="m-0 text-sm font-mono leading-relaxed">
            <code 
              dangerouslySetInnerHTML={{ 
                __html: hljs.highlight(activeContent, { language: getHighlightLanguage(activeTab) }).value 
              }} 
            />
          </pre>
        </div>
      </div>

      {/* SETUP.md preview if it exists */}
      {setupInstructions && (
        <div className="border-t border-border bg-[#151515]">
          <div className="p-4 border-b border-white/5">
            <h3 className="font-semibold flex items-center gap-2">
              📋 Setup Instructions
            </h3>
          </div>
          <div className="p-4 bg-surface max-h-48 overflow-y-auto custom-scrollbar text-sm text-white/80 whitespace-pre-wrap font-body">
            {setupInstructions}
          </div>
        </div>
      )}
    </div>
  );
}
